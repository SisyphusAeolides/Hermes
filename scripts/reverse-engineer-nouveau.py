def emit_superiority(manifest: dict, inv: dict) -> str:
    return f"""# Hermes vs Nouveau GSP (generated)

Source inventory: **{inv['file_count']}** files, **{inv['total_lines']}** lines under Nouveau tree.

## Firmware tables extracted

| Kind | Count |
|---|---:|
| BOOTER declarations | {len(manifest['booter_firmware'])} |
| FMC declarations | {len(manifest['fmc_firmware'])} |
| fwif table rows | {len(manifest['fwif_entries'])} |

## Where Hermes is designed to be better

| Area | Nouveau | Hermes |
|---|---|---|
| Missing firmware | Often probe error (`gsp ctor failed`) after partial bind | **Fail-closed admission** before Online; no invented GPU |
| Firmware identity | Path/version load | Path + **SHA-256 pin** + **ELF structure** (`.fwimage`/`.fwversion`) |
| Online publication | Running flag after RM path | **Manifold certificate** (IOMMU+WPR+mailbox+ready+features) |
| Languages | C | Rust + Austral + Idris + Agda |
| Drop-in NVIDIA names | DRM `nouveau` | Parallel `nvidia*` personality **and** Nouveau-shaped DRM model |
| Formal gates | Implicit | Explicit total/safe/linear models |

## Shared truth with Nouveau

- linux-firmware chip paths: `nvidia/<chip>/gsp/{{booter_*,bootloader,fmc,gsp}}-<ver>.bin`
- RM API generations **r535** and **r570**
- Turing Booter path vs Hopper/Blackwell FMC path
- Signature section names like `.fwsignature_tu10x`

Hermes does **not** delete Nouveau; it re-hosts the same firmware binding knowledge under a stricter Online policy and dual ABI (NVIDIA-named + DRM).
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--nouveau",
        type=Path,
        required=True,
        help="Path to drivers/gpu/drm/nouveau",
    )
    ap.add_argument(
        "--out",
        type=Path,
        default=Path("generated/nouveau-re"),
        help="Output directory",
    )
    args = ap.parse_args()
    nouveau: Path = args.nouveau
    if not nouveau.is_dir():
        print(f"error: nouveau tree not found: {nouveau}", file=sys.stderr)
        return 2

    gsp = nouveau / "nvkm" / "subdev" / "gsp"
    if not gsp.is_dir():
        print(f"error: GSP subdir missing under {nouveau}", file=sys.stderr)
        return 2

    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    (out / "formal").mkdir(exist_ok=True)

    inv = inventory_tree(nouveau)
    manifest = parse_gsp_firmware(gsp)

    (out / "inventory.json").write_text(json.dumps(inv, indent=2) + "\n")
    (out / "gsp_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (out / "firmware_manifest.rs").write_text(emit_rust_firmware(manifest))
    (out / "superiority.md").write_text(emit_superiority(manifest, inv))
    (out / "formal" / "NvkmGsp.idr").write_text(emit_idris(manifest))
    (out / "formal" / "NvkmGsp.agda").write_text(emit_agda(manifest))
    (out / "formal" / "NvkmGsp.aui").write_text(emit_austral_aui())
    (out / "formal" / "NvkmGsp.aum").write_text(emit_austral_aum())

    print(f"wrote {out}")
    print(f"  files={inv['file_count']} lines={inv['total_lines']}")
    print(
        f"  booter={len(manifest['booter_firmware'])} fmc={len(manifest['fmc_firmware'])} fwif={len(manifest['fwif_entries'])}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
